/**
 * ميزانيّة الجلب — مهلةٌ لكلّ نداءٍ إلى الواجهة الخلفيّة.
 *
 * ─── العطل المقيس ───
 *
 * `fetch` بلا `signal` ينتظر إلى الأبد. وثلاثة عشر من أربعة عشر موضع جلبٍ
 * في المتجر كانت بلا مهلة. والأثر قيس بوسيطٍ يقبل الوصلة ولا يردّ: **كلّ**
 * صفحةٍ جُرِّبت لم تردّ خلال خمس عشرة ثانية — لا خطأ، ولا حالة فراغٍ
 * صادقة، ولا مخرج. لسانُ حالٍ أسوأ من الانقطاع نفسه: الانقطاع يُرسم بطاقةَ
 * تعذّرٍ فيها زرّ، والتعليق يترك لسانًا يدور بلا نهاية.
 *
 * ─── ولماذا أرقامٌ مسمّاة لا رقمٌ واحد ───
 *
 * موضع النداء من مسار الطلب هو ما يحدّد ما يُحتمل انتظاره. والوسيط يقع على
 * **كلّ** طلبٍ فلا يحتمل ما تحتمله صفحة، وكتابةٌ يبدؤها الزائر تحتمل ما لا
 * تحتمله ورقة أنماطٍ حاجبة للتصيير.
 *
 * وانقضاءُ المهلة يرمي، والملتقِط في كلّ موضعٍ يردّ «لا بيانات» — وهو
 * المسار الصادق الذي كان مرسومًا أصلًا ولم يكن يُبلَغ أبدًا.
 */

/*
 * والأرقام تُجمع، فتُحسب من أعمق سلسلة لا من نداءٍ واحد.
 *
 * قيس بوسيطٍ لا يردّ: الصفحة الرئيسة تُطلق ثلاثة عشر نداءً، والسلّة أربعة —
 * وكلتاهما انتظرت ‎9.5s‎ نفسها. أي أنّ النداءات متوازية في موجات، والعمق
 * ثلاثٌ: الوسيط، ثمّ بيانات التخطيط والصفحة، ثمّ شريطُ التذييل الذي لا
 * يبدأ قبلها. فالسقف الفعليّ حاصلُ جمع الموجات الثلاث لا أكبرها.
 *
 * والنداء السليم يردّ في ‎~50ms‎ — فـ‎2.5s‎ خمسون ضعفًا، متّسعٌ لخادمٍ بطيء
 * وضيّقٌ على خادمٍ معلَّق. وأسوأ حالٍ بهذه الأرقام ‎~6s‎ إلى صفحةٍ تُعلن
 * العطل وتعطي مخرجًا، بدل انتظارٍ بلا نهاية.
 */
export const FETCH_BUDGET = {
  /** الوسيط: على مسار كلّ طلب. تأخّرُه تأخّرُ الموقع كلّه. */
  edge: 1_200,
  /** أصولٌ تحجب التصيير (ورقة رموز الثيم): بعدها تُخدم الافتراضات. */
  chrome: 2_000,
  /** بيانات صفحةٍ تُصيَّر في الخادم. هدف LCP ‎2.5s‎ يحكم السقف. */
  page: 2_500,
  /** كتابةٌ يبدؤها الزائر وينتظرها بعينه: أطول، ومحدودة. */
  action: 10_000,
} as const;

export type FetchBudget = keyof typeof FETCH_BUDGET;

/**
 * إشارةُ إجهاضٍ بميزانيّة الموضع.
 *
 * تُمرَّر `signal` وحدها كي يبقى كلّ ما سواها (`cache`/`next`/`headers`)
 * بيد موضع النداء — الميزانيّة لا تعرف سياسة التخزين ولا يجب أن تعرفها.
 */
export function budget(kind: FetchBudget = 'page'): AbortSignal {
  return AbortSignal.timeout(FETCH_BUDGET[kind]);
}
