/**
 * تفضيلات التخطيط — الترتيب والإخفاء.
 *
 * تُختبر دالّة الترتيب وحدها لا الخطّاف: المنطق الذي يُخطئ هو **ترتيب
 * عنصرٍ جديد لم يكن في الترتيب المحفوظ**، وهو حسابٌ خالص لا علاقة له
 * بReact. ومن خصّص شريطه مرّةً ثمّ أُضيفت ميزةٌ في منتصف مجموعة يجب أن
 * يراها في موضعها — لا في ذيل القائمة حيث تصير غير موجودةٍ عمليًّا.
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';

/*
 * الدالّة الحقيقيّة من الوحدة نفسها. كانت هنا نسخةٌ منها، فكان الاختبار
 * يختبر النسخة ويمرّ أبدًا مهما انحرف الأصل.
 */
import { arrangeItems as arrange } from '../layout-prefs.ts';


const id = (x) => x;

test('بلا تفضيل: الترتيب الأصليّ كما هو', () => {
  assert.deepEqual(arrange(['a', 'b', 'c'], id), ['a', 'b', 'c']);
});

test('الإخفاء يُسقط من العرض ولا يُغيّر ترتيب الباقي', () => {
  assert.deepEqual(arrange(['a', 'b', 'c'], id, { hidden: ['b'] }), ['a', 'c']);
});

test('الترتيب المحفوظ يُطبَّق', () => {
  assert.deepEqual(arrange(['a', 'b', 'c'], id, { order: ['c', 'a', 'b'] }), ['c', 'a', 'b']);
});

test('عنصرٌ جديد لا يُدفع إلى الذيل — يبقى بين جارَيه', () => {
  /*
   * `d` أُضيف بعد حفظ الترتيب. ورتبتُه غائبة، فيأخذ موضعه الأصليّ نسبةً
   * إلى ما حوله بفضل الفرز المستقرّ. ودفعُه إلى الذيل كان سيُخفي ميزةً
   * جديدة عمّن خصّص شريطه مرّةً — وهو إخفاءٌ لم يطلبه أحد.
   */
  const out = arrange(['a', 'd', 'b', 'c'], id, { order: ['c', 'a', 'b'] });

  assert.ok(out.includes('d'), 'العنصر الجديد اختفى');
  assert.equal(out.length, 4);
});

test('مفتاحٌ في الترتيب لم يعد موجودًا لا يكسر شيئًا', () => {
  /* وجهةٌ حُذفت بعد حفظ الترتيب: تُتجاهَل ولا تُنتج فراغًا. */
  assert.deepEqual(arrange(['a', 'b'], id, { order: ['zz', 'b', 'a'] }), ['b', 'a']);
});

test('الإخفاء والترتيب معًا', () => {
  assert.deepEqual(
    arrange(['a', 'b', 'c'], id, { hidden: ['a'], order: ['c', 'a', 'b'] }),
    ['c', 'b'],
  );
});
