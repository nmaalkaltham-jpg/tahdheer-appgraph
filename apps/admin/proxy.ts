/**
 * بوّابة `/dev/*` — الحجب قبل التصيير، لا داخله.
 *
 * ─── لماذا وسيطٌ وقد كان الشرط في تخطيطٍ ───
 *
 * كان المنع في `app/dev/layout.tsx` وحده: `notFound()` حين `NODE_ENV=production`.
 * وهو **لا يمنع**. مقيسٌ على بناء إنتاجٍ كامل (Next 16.3.3، `next start`):
 *
 *   موضع البوّابة                         `/dev/*` (أُزيلت)
 *   `app/dev/layout.tsx` (الحال السابقة)   200 · 463 ك.ب · البيانات كاملة
 *   صدفة الورشة (تخطيطٌ يُصيَّر يقينًا)      200 · 350 ك.ب
 *   وسيطٌ قبل التصيير (الحال الآن)          404 · 0 بايت
 *
 * السطران الأوّلان كلاهما تسريب. الأوّل لأنّ ذلك التخطيط لا يُصيَّر أصلًا
 * (رُقِّعت نسخته المُصرَّفة لتنادي `notFound()` بلا شرط فلم يتغيّر الجواب).
 * والثاني لأنّ `notFound()` من تخطيطٍ في هذه النسخة يُسقط مخرَج التخطيط
 * نفسه ثمّ **يُكمل** تصيير الصفحة: الجواب يحمل `NEXT_HTTP_ERROR_FALLBACK`
 * وحمولة RSC وفيها أسماء الحرّاس، ورمزه 200.
 *
 * فالحدّ الوحيد الذي لا يُصيَّر خلفه شيء هو ما يسبق التصيير.
 *
 * ─── ولماذا 404 عارية لا صفحة خطأ ───
 *
 * الورشة تعرض طوبولوجيا المسارات والصلاحيات والجداول — خريطة سطح الهجوم.
 * وصفحة خطأٍ مصمَّمة تُثبت أنّ المسار معروفٌ للتطبيق؛ الجواب الفارغ لا
 * يُفرَّق عن مسارٍ لا وجود له.
 *
 * ─── وبابٌ صريح للبيئات الوسيطة ───
 *
 * `ARCH_WORKBENCH=1` يفتحها في نشرٍ غير إنتاجيّ (بيئة اختبار داخليّة).
 * متغيّر خادم لا `NEXT_PUBLIC_` — الأخير يُحقن في حزمة المتصفّح فيصير
 * إعلانًا عن وجود الباب لكل زائر.
 */

/*
 * يستخدم Next.js 16 اصطلاح `proxy.ts` لاعتراض الطلب قبل تصيير الصفحة.
 * تبقى البوابة محصورة في `/dev` وما تحته عبر `config.matcher`.
 */
import { NextResponse, type NextRequest } from 'next/server';

export function proxy(_request: NextRequest) {
  const isProduction = process.env.NODE_ENV === 'production';
  const explicitlyOpened = process.env.ARCH_WORKBENCH === '1';

  if (isProduction && !explicitlyOpened) return new NextResponse(null, { status: 404 });

  return NextResponse.next();
}

/*
 * المُطابِق يحصر الوسيط في `/dev` وما تحته وحدها: بقيّة اللوحة لا تدفع
 * ثمن وسيطٍ على كل طلب.
 */
export const config = {
  matcher: ['/dev', '/dev/:path*'],
};
