<?php

namespace App\Domain\Insights;

/**
 * عقد المُجمِّع — كلّ نطاقٍ يجيب السؤال نفسه بمصادره هو.
 *
 * الواجهة تُبقي طبقة التجميع واحدة: وحدة التحكّم لا تعرف شيئًا عن البحث ولا
 * عن السلال، وإضافة نطاقٍ لا تمسّها. وهذا هو الفرق بين طبقة تجميعٍ موحّدة
 * واستعلاماتٍ متناثرة في كلّ مكوّن.
 */
interface InsightAggregator
{
    /**
     * مؤشّرات النطاق — مقيسةً أو مُعلَنةَ الغياب.
     *
     * @return list<Metric>
     */
    public function metrics(InsightWindow $window): array;

    /**
     * القوائم التي يُحقَّق فيها: أعلى الاستعلامات، المنتجات بلا مبيعات، وما شابه.
     *
     * تُفصل عن المؤشّرات لأنّها تُحمَّل وتُعرض بشكلٍ مختلف، ولأنّ لوحةً قد
     * تعرض المؤشّرات وحدها.
     *
     * @return array<string, mixed>
     */
    public function lists(InsightWindow $window): array;
}
