<?php

namespace App\Domain\SEO;

/**
 * مسار أرشيف التصنيف — تعريف واحد يشترك فيه كل من يبني هذه العناوين.
 *
 * سلاسل التصنيف ليست كلّها صالحة لمسار: اثنتا عشرة مادة من ثماني عشرة، وثلاثة
 * أنواع من سبعة، تحمل مسافة («اللغة الإنجليزية»، «عرض بوربوينت»). المسافة في
 * جزء المسار لا تُكتب إلا `%20`، فيصير العنوان القانوني وكل مدخل في الخريطة
 * يحمل تسلسل هروب — وهي عناوين الذيل الطويل التي يقوم عليها ظهور المتجر.
 *
 * المسافة تصير شرطة في **المسار وحده**؛ المرشِّح يبقى على القيمة الحقيقية،
 * لأنها المفردة التي فُهرست. ولأن أي سلسلة هنا لا تحمل شرطة أصلًا، التحويل
 * عكوسٌ على هذه المفردات — ومع ذلك تجد الواجهة المصطلح بالمطابقة لا بالعكس.
 *
 * النظير في المتجر: `termSegment()` في
 * `apps/storefront/app/(catalog)/_components/dimensions.ts`. القاعدتان يجب أن
 * تبقيا واحدة، وإلّا أعلنت الخريطة عنوانًا يردّ 404.
 */
final class TaxonomyPath
{
    /** جزء المسار الذي يمثّل هذه السلسلة. */
    public static function segment(string $slug): string
    {
        return str_replace(' ', '-', $slug);
    }

    /** المسار الكامل، مثل `/subjects/اللغة-الإنجليزية`. */
    public static function join(string $prefix, string $slug): string
    {
        return rtrim($prefix, '/').'/'.self::segment($slug);
    }
}
