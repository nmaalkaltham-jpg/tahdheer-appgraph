<?php

declare(strict_types=1);

namespace App\Domain\ContentIntelligence\Entities;

/**
 * موقف المرشَّح من قيمة الفهرس — أربعُ حالاتٍ لا اثنتان.
 *
 * «يوافق/يخالف» وحدهما يكذبان: منتجٌ حقلُه فارغ ليس مخالفًا (لا قيمة
 * تُخالَف) وليس موافقًا (لا قيمة تُوافَق) — وهو **بالضبط** الحالة التي بُني
 * هذا الجدول لأجلها: منتجٌ بلا بيانات وصفيّة يملأها الشاهد. ودمجُها في
 * «يخالف» يُغرق المخالفات الحقيقيّة — وهي وحدها ما يستحقّ نظر إنسان.
 *
 * و`NoProduct` منفصلة عن `CatalogMissing`: أصلٌ لا منتجَ مربوطًا به لا فهرسَ
 * له أصلًا، فغيابُ القيمة ليس نقصًا في المنتج بل غيابُ المنتج نفسه. خلطُهما
 * يجعل تقرير «كم منتجًا ينقصه الوصف» يعدّ أصولًا يتيمة.
 */
enum EntityAgreement: string
{
    /** الفهرس يقول ما يقوله الشاهد. المرشَّح يؤكّد ولا يضيف. */
    case Agree = 'agree';

    /** الفهرس يقول غير ما يقوله الشاهد. هذه وحدها تستحقّ نظر إنسان. */
    case Disagree = 'disagree';

    /** المنتج موجود وحقلُه فارغ — الشاهد يملأ فراغًا لا يُصحّح خطأً. */
    case CatalogMissing = 'catalog_missing';

    /** لا منتج مربوطٌ بهذا الأصل — لا فهرسَ يُقارَن به. */
    case NoProduct = 'no_product';

    /** @return array<int, string> */
    public static function values(): array
    {
        return array_map(fn (self $a) => $a->value, self::cases());
    }
}
