<?php

declare(strict_types=1);

namespace App\Domain\ContentIntelligence;

/**
 * حالة الاستخراج — أربعُ حالاتٍ لا اثنتان.
 *
 * «نجح/فشل» وحدهما يكذبان في هذا النطاق: مستخرِجٌ يعجز عن صيغةٍ ليس فاشلًا
 * (لا عطبَ ولا إعادةَ تُصلحه) وليس ناجحًا (لا نصّ). فصلُ `CapabilityGap` عن
 * `Failed` هو الفرق بين «ثبّت أداةً» و«أعد المحاولة»، وبين عجزٍ يُقال وعجزٍ
 * يُخفى وراء صفٍّ ناجحٍ فارغ.
 *
 * و`Partial` تمنع الكذبة المعاكسة: نصٌّ استُخرج بعضُه يُعلَن بعضًا ولا
 * يُعلَن كلًّا — وإلّا ظنّ القارئ أنّ ما غاب غيرُ موجود.
 */
enum ExtractionStatus: string
{
    /** نصّ الصيغة كلّه استُخرج أصليًّا. */
    case Ok = 'ok';

    /** بعضُه استُخرج، وما تعذّر مسمًّى في `meta.capability`. */
    case Partial = 'partial';

    /** لا قدرة على هذه الصيغة — لا عطب. `meta.requires` يسمّي الناقص. */
    case CapabilityGap = 'capability_gap';

    /** عطلٌ يُعاد: تخزينٌ غائب، بايتات فاسدة، بصمةٌ لا تطابق. */
    case Failed = 'failed';

    /**
     * هل هذه الحالة نهائيّةٌ لهذه البايتات وهذه النسخة؟
     *
     * الفاشل وحده يُعاد تلقائيًّا. والعجز المعلَن لا يُعاد بإلحاحٍ على
     * الأمر — يُعاد برفع `extractor_version` حين تصل القدرة فعلًا، وإلّا
     * صار كلّ تشغيلٍ يقرأ الملفّات كلّها ليُنتج الجواب نفسه.
     */
    public function isTerminal(): bool
    {
        return $this !== self::Failed;
    }
}
