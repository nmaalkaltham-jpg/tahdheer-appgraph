 * أصل المتجر العامّ — مصدر كل رابط مطلق يُصدره نطاق SEO.
 *
 * لماذا يوجد هذا الملفّ: كان `SiteIdentity::origin()` يسقط على
 * `config('app.url')` حين لا يجد شيئًا، و`app.url` في الإنتاج هو
 * `https://api.tahdheer.com` — مضيف الـAPI. النتيجة المقيسة على الإنتاج:
 *
 *   · كل صفحة منتج تُعلن <link rel="canonical"> يشير إلى مضيف يخدم JSON.
 *   · robots.txt يُعلن `Host: https://api.tahdheer.com` وخريطة موقع تُعيد 404.
 *   · كل @id في البيانات المُهيكلة على المضيف الخطأ.
 *
 * أي: المتجر يخبر محرّكات البحث أن نسخته المعيارية في مكان لا صفحات فيه.
 * لا خطأ ولا تحذير — فقط متجر غير قابل للفهرسة.
 *
 * `env()` هنا تُقرأ وقت بناء الإعداد لا وقت الطلب، فتنجو من `config:cache`.
 * و`FRONTEND_URL` يمرّرها compose أصلًا للحاوية (docker-compose.yml) — كانت
 * القيمة الصحيحة حاضرة وغير مستعملة.
 */

return [

    'site_url' => env('SEO_SITE_URL', env('FRONTEND_URL')),

    /*
     * المضيفون المسموح بالتحويل إليهم خارج المتجر — فارغة افتراضيًّا.
     *
     * كان `normalizeTarget` يقبل أي عنوان يبدأ بـ«http» حرفيًّا، فأي قاعدة
     * تحويل تستطيع أن تُرسل زوّار المتجر إلى موقع خارجي بثقة النطاق: إعادة
     * توجيه مفتوحة، وهي ناقل تصيّد معروف. الافتراض الآمن هو الرفض، والاستثناء
     * يُعلَن مضيفًا مضيفًا (نطاق قديم أثناء ترحيل، مثلًا).
     */
    'redirect_allowed_hosts' => array_values(array_filter(array_map(
        'trim',
        explode(',', (string) env('SEO_REDIRECT_ALLOWED_HOSTS', '')),
    ))),

];
