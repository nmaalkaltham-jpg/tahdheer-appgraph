/**
 * FaqList — الأسئلة الشائعة.
 *
 * منقول من موضع النداء الحقيقي في صفحة المنتج
 * (‎components/product/ProductFaqs.tsx‎): عنوان ثابت «الأسئلة الشائعة»
 * و‎openMode="multi"‎ ومعرّف قسم صريح.
 *
 * الأسئلة نفسها ليست مخترَعة ولا لوريم: كلٌّ منها يسأل عن **حقل يصدره
 * الكتالوج فعلًا** — الصيغة (`format`) وقابلية التعديل (`editable`) وعدد
 * الصفحات (من `facts[]`) والتسليم الفوري بعد الدفع. وهذا هو الاستعمال
 * الصحيح للمكوّن: هو لا يشحن نصًّا خاصًّا به، وكل سؤال وجواب يصله خاصّيةً.
 *
 * ‎<details>‎ بلا حالة React، فالخلايا أدناه تُصيَّر مطويّة كما يراها الزائر
 * أوّل مرة — عدا خليّة واحدة تُفتح صراحةً لتُظهر شكل الجواب.
 *
 * ‎domId‎ مختلف في كل خليّة عمدًا: هو ما يمنع تصادم معرّفات العناوين، وفي
 * ‎single‎ هو أيضًا اسم المجموعة الذي يجعل فتح سؤالٍ يغلق أخاه.
 */

import { FaqList, type FaqItem } from '@tahdheer/ui';

