/**
 * TracingBeam — خطٌّ يتتبّع التمرير بجانب محتوًى طويل.
 *
 * ─── ما هو، ولماذا الأبناء طويلون هنا ───
 *
 * الخطّ يقيس **تقدّمك في المحتوى**: يمتدّ مع التمرير من أوّل الكتلة إلى
 * آخرها. فمحتوًى قصيرٌ يجعله بلا معنى — لا شيء يُتتبَّع. ولذلك كلّ خليّةٍ
 * أدناه تلفّ كتلةً حقيقيّةً متعدّدة الأقسام، لا فقرةً واحدة.
 *
 * ─── وما لا تُظهره اللقطة ───
 *
 * التقدّم يُحسب من موضع الكتلة في نافذة العرض (`--beam-progress` تُضبط أثناء
 * التمرير). البطاقة إطارٌ واحد: الخطّ عند بدايته، وهو ما يراه الزائر قبل أن
 * يمرّر.
 *
 * وفي `prefers-reduced-motion` يضبط المكوّن التقدّم على `1` فورًا — أي الخطّ
 * مكتملًا بلا حركة. فمن طلب تقليل الحركة يرى المؤشّر كاملًا لا معطَّلًا،
 * وهذا سلوكٌ مقصود يستحقّ أن يُقرأ في الوثيقة لا أن يُكتشَف.
 */

import { TracingBeam } from '@tahdheer/ui';

function Step({ n, title, body }: { n: number; title: string; body: string }) {
  return (
    <section style={{ display: 'grid', gap: 8, paddingBlock: 18 }}>
      <span style={{ fontSize: 12, fontWeight: 800, color: 'var(--green-700, #1e7355)' }}>
        الخطوة {n}
      </span>
      <b style={{ fontSize: 17, color: 'var(--ink, #14261d)' }}>{title}</b>
      <p style={{ margin: 0, fontSize: 13.5, lineHeight: 1.9, color: 'var(--text-secondary, #5b6b62)' }}>
        {body}
      </p>
    </section>
  );
}

const cell: React.CSSProperties = { direction: 'rtl', maxWidth: 560 };

/** كتلةٌ من ثلاث خطوات — أقصر محتوًى يبقى الخطّ فيه ذا معنى. */
export function Default() {
  return (
    <div style={cell}>
      <TracingBeam>
        <Step n={1} title="ضيّق بالمنهج" body="المرحلة ثمّ الصفّ ثمّ المادّة والفصل — التصنيف نفسه الذي يُبنى عليه المنهج." />
        <Step n={2} title="اختر الصيغة" body="Word للتعديل، أو PowerPoint للعرض، أو PDF للطباعة. السعر يتبع الصيغة." />
        <Step n={3} title="استلِم فورًا" body="رابط التنزيل يصل بعد إتمام الدفع مباشرةً، ويبقى محفوظًا في حسابك." />
      </TracingBeam>
    </div>
  );
}

