/**
 * Tabs — تبويباتٌ بنسقين.
 *
 * كالأكورديون: النسقان مدخلان مستقلّان في سجلّ المكوّنات
 * (`tabs/underline` و`tabs/side`)، كلاهما `exists`. والخليّتان الأوليان هما
 * ذانك المدخلان لا تنويعٌ عليهما.
 *
 * ─── المحتوى: ما يسأل عنه المعلّم فعلًا ───
 *
 * الألواح تصف محتوى ملفٍّ من الكتالوج — ما فيه، وكيف يُسلَّم، ولمن يصلح.
 * وهي البنية نفسها التي يحملها الأكورديون (`text` ثمّ `points`)، لأنّ
 * `DisclosureBody` واحدٌ يخدم الاثنين.
 *
 * ─── وما لا تُظهره اللقطة ───
 *
 * التبويب الأوّل وحده مفتوح في التصيير الساكن — وهو ما يراه الزائر أوّل
 * مرّة. تبديلُ الألواح تفاعلٌ يُختبَر بالنقر، ولا تُظهره صورة.
 */

import { Tabs, type TabItem } from '@tahdheer/ui';

const ITEMS: readonly TabItem[] = [
  {
    label: 'ما في الملفّ',
    text: 'تحضيرٌ كامل لوحدةٍ دراسيّة، مرتّبٌ على حصص، وجاهزٌ للطباعة أو العرض.',
    points: ['أهداف الدرس وخطواته', 'أوراق نشاطٍ للطالب', 'أسئلة تقويمٍ بإجاباتها'],
  },
  {
    label: 'الصيغ والتسليم',
    text: 'تختار الصيغة على بطاقة المنتج، ويصل الرابط فور إتمام الدفع.',
    points: ['Word للتعديل', 'PowerPoint للعرض', 'PDF للطباعة'],
  },
  {
    label: 'لمن يصلح',
    text: 'مبنيٌّ على المنهج السعوديّ، ومصنَّفٌ بالمرحلة والصفّ والمادّة والفصل — فما تختاره هو ما تُدرّسه.',
  },
];

const cell: React.CSSProperties = { direction: 'rtl', maxWidth: 560 };

/** `underline` — خطٌّ تحت التبويب النشط. النسق الأوّل في السجلّ. */
export function Underline() {
  return (
    <div style={cell}>
      <Tabs items={ITEMS} layout="underline" domId="tabs-underline" ariaLabel="تفاصيل الملفّ" />
    </div>
  );
}

/** `side` — التبويبات عمودٌ جانبيّ واللوح بجانبها. النسق الثاني. */
export function Side() {
  return (
    <div style={cell}>
      <Tabs items={ITEMS} layout="side" domId="tabs-side" ariaLabel="تفاصيل الملفّ" />
    </div>
  );
}

/**
 * لوحٌ بنصٍّ بلا نقاط — البنية اختياريّة لا إلزاميّة.
 *
 * `DisclosureBody` يقبل `text` أو `points` أو كليهما، ولوحٌ بفقرةٍ واحدة
 * استعمالٌ مشروع لا حالةٌ ناقصة.
 */
export function TextOnly() {
  return (
    <div style={cell}>
      <Tabs
        items={[
          { label: 'الاسترجاع', text: 'الملفّ الرقميّ حين يُنزَّل لا يعود، فالاسترجاع يُدرَس حالةً بحالة قبل التنزيل.' },
          { label: 'الدعم', text: 'سؤالٌ عن ملفٍّ اشتريتَه يصل الدعم من حسابك، ويُربط بالطلب تلقائيًّا.' },
        ]}
        layout="underline"
        domId="tabs-text"
        ariaLabel="السياسات"
      />
    </div>
  );
}
