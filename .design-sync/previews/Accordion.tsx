/**
 * Accordion — كشفٌ تدريجيّ بنسقين.
 *
 * النسقان ليسا زينةً ولا اختيارَ مؤلِّف المعاينة: سجلّ المكوّنات
 * (`packages/registry/src/registry.ts`) يسجّلهما مدخلين مستقلّين —
 * `accordion/cards` و`accordion/soft` — وكلاهما `exists`. فالخليّتان الأوليان
 * أدناه هما ما يعرضه السجلّ نفسه، لا تنويعًا مخترَعًا عليه.
 *
 * ─── المحتوى من الكتالوج لا من لوريم ───
 *
 * البنود تصف ما يصله المشتري فعلًا: الصيغ التي يصدرها الكتالوج
 * (Word · PowerPoint · PDF)، والتسليم الفوري بعد الدفع، ورخصة الاستعمال.
 * وهي أسئلةٌ يطرحها معلّمٌ قبل الشراء، لا نصٌّ يملأ فراغًا.
 *
 * ─── و«الفتح المفرد» فرقُه سلوكيّ لا بصريّ ───
 *
 * `singleOpen` يبثّ سمة `name` مشتركة على كلّ `<details>` — فتحُ بندٍ يغلق
 * أخاه، بلا سطر جافاسكربت. واللقطة الساكنة لا تُظهر ذلك: الخليّة تبدو كأختها
 * وهي مطويّة. لا أفتحها بحيلةٍ هنا — المكوّن لا يكشف خاصّية `open`، وإظهار
 * حالةٍ لا ينتجها المكوّن كذبٌ على قارئ البطاقة.
 *
 * ─── و`domId` مختلفٌ في كلّ خليّة عمدًا ───
 *
 * هو ما يمنع تصادم معرّفات العناوين حين تجتمع الخلايا في صفحةٍ واحدة، وهو
 * نفسه اسم المجموعة في `singleOpen`.
 */

import { Accordion, type AccordionItem } from '@tahdheer/ui';

const ITEMS: readonly AccordionItem[] = [
  {
    title: 'ما الذي أستلمه بعد الشراء؟',
    text: 'ملفٌّ واحد بالصيغة التي اخترتها على صفحة المنتج، يصل رابطُه فور إتمام الدفع ويبقى في حسابك.',
    points: ['Word — قابل للتعديل كاملًا', 'PowerPoint — عرضٌ جاهز للحصّة', 'PDF — للطباعة المباشرة'],
  },
  {
    title: 'هل أستطيع تعديل الملفّ؟',
    text: 'الملفّات المعلَّمة «قابلة للتعديل» تُفتح ببرنامجك وتُحرَّر بلا قيد — والبطاقة تقول ذلك قبل الشراء لا بعده.',
  },
  {
    title: 'رخصة الاستعمال',
    text: 'الاستعمال لفصولك أنت.',
    points: ['استعمالٌ صفّيّ غير محدود', 'لا إعادة بيع ولا نشر عامّ', 'النسخة محفوظة في حسابك للتحميل مجدّدًا'],
  },
];

const cell: React.CSSProperties = { direction: 'rtl', maxWidth: 560 };

/** `cards` — النسق الأوّل في السجلّ: كلّ بندٍ بطاقةٌ مستقلّة بحدّها. */
export function Cards() {
  return (
    <div style={cell}>
      <Accordion title="قبل أن تشتري" items={ITEMS} layout="cards" domId="acc-cards" />
    </div>
  );
}

/** `soft` — النسق الثاني: مطويّاتٌ ناعمة بفواصل بدل البطاقات. */
export function Soft() {
  return (
    <div style={cell}>
      <Accordion title="قبل أن تشتري" items={ITEMS} layout="soft" domId="acc-soft" />
    </div>
  );
}

/** الفتح المفرد — الفرق في `name` داخل الترميز، ويُختبَر بالنقر لا باللقطة. */
export function SingleOpen() {
  return (
    <div style={cell}>
      <Accordion title="فتحٌ مفرد" items={ITEMS} layout="cards" singleOpen domId="acc-single" />
    </div>
  );
}

/**
 * بلا عنوان — حين يسبق القسمَ عنوانٌ أعلى في الصفحة فلا يُكرَّر.
 *
 * والعقد صريح: العنوان الفارغ يعني **لا** عنوان و**لا** `aria-labelledby`
 * يشير إلى عنصرٍ غير موجود — إشارةٌ معلَّقة أسوأ من غياب التسمية.
 */
export function Untitled() {
  return (
    <div style={cell}>
      <Accordion items={ITEMS} layout="soft" domId="acc-untitled" />
    </div>
  );
}
